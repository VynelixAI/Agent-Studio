/** Catalog of installable DE / DB plugins and their connector forms */

export type PluginFieldKind = "text" | "password" | "number" | "select";

export interface PluginField {
  key: string;
  label: string;
  kind: PluginFieldKind;
  /** If true, value is stored encrypted via secretRef — never in YAML plaintext */
  secret?: boolean;
  required?: boolean;
  placeholder?: string;
  options?: Array<{ value: string; label: string }>;
  group: "connection" | "auth" | "target";
  help?: string;
}

export interface PluginDef {
  id: string;
  name: string;
  vendor: string;
  category: "database" | "warehouse" | "lake" | "streaming" | "platform" | "workflow" | "custom";
  description: string;
  /** Connector type written into workspace YAML */
  connectorType: string;
  accent: string;
  /** Short badge */
  badge: string;
  fields: PluginField[];
  /** Example node types unlocked after install */
  unlocks: string[];
  /** True when created by the customer (not built-in catalog) */
  custom?: boolean;
}

