export function getPlugin(id: string): PluginDef | undefined {
  return getAllPlugins().find((p) => p.id === id);
}

export const PLUGIN_STORAGE_KEY = "vynelix-installed-plugins";
export const CUSTOM_PLUGIN_STORAGE_KEY = "vynelix-custom-plugins";

export function loadCustomPlugins(): PluginDef[] {
  try {
    const raw = localStorage.getItem(CUSTOM_PLUGIN_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as PluginDef[];
    return Array.isArray(parsed)
      ? parsed.filter((p) => p && typeof p.id === "string" && Array.isArray(p.fields))
      : [];
  } catch {
    return [];
  }
}

export function saveCustomPlugins(plugins: PluginDef[]) {
  localStorage.setItem(CUSTOM_PLUGIN_STORAGE_KEY, JSON.stringify(plugins));
}

/** Built-in catalog + customer-defined dynamic plugins */
export function getAllPlugins(): PluginDef[] {
  const custom = typeof localStorage !== "undefined" ? loadCustomPlugins() : [];
  const builtinIds = new Set(PLUGIN_CATALOG.map((p) => p.id));
  // Custom overrides same id only if explicitly custom (avoid collisions with builtins)
  const safeCustom = custom.filter((p) => !builtinIds.has(p.id) || p.custom);
  return [...PLUGIN_CATALOG, ...safeCustom.filter((p) => !builtinIds.has(p.id))];
}

export function upsertCustomPlugin(plugin: PluginDef): PluginDef {
  const next = {
    ...plugin,
    custom: true,
    category: plugin.category || ("custom" as const),
  };
  const existing = loadCustomPlugins().filter((p) => p.id !== next.id);
  // Never overwrite a built-in id
  if (PLUGIN_CATALOG.some((p) => p.id === next.id)) {
    throw new Error(`Plugin id “${next.id}” is reserved by a built-in plugin`);
  }
  saveCustomPlugins([...existing, next]);
  return next;
}

export function deleteCustomPlugin(id: string) {
  saveCustomPlugins(loadCustomPlugins().filter((p) => p.id !== id));
}

/** Slugify a display name into a stable plugin / connector id */
export function slugifyPluginId(name: string): string {
  return (
    name
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .replace(/^_|_$/g, "")
      .slice(0, 48) || `custom_${Date.now().toString(36)}`
  );
}

export function createEmptyCustomField(): PluginField {
  return {
    key: "",
    label: "",
    kind: "text",
    group: "connection",
    required: false,
    secret: false,
  };
}
